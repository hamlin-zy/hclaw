/** 侧栏宽度降级档位（spec §5.3.4）。阈值集中在此，禁散落到组件里硬编码。 */
export type WidthTier = 'full' | 'narrow' | 'tight'

/**
 * ≥320 完整 / 270–319 窄 / <270 极窄。
 *
 * 阈值按「项目名的最小可用宽度」重算（2026-09-24 用户拍板，取代原 240 / 200）：
 * 段头固定列合计 chev 12 + 分支 ≤84 + 条数 44 + 操作 ≤46 + 列间距 24 + 段头内边距 16 ≈ 226px，
 * 而侧栏 clamp 下限是 180 —— 原阈值下 240 宽就判定「完整五列」，留给项目名的只剩十几像素，
 * 真机上项目名被压成「rea…」。提档后：≥320 完整五列（默认宽度即此档，条数常显）；
 * 270–319 收起条数；<270 再收起分支（操作入口任何宽度下都不消失）。
 * 分支列与操作列均为 fit-content：无分支 / 未分组段不占轨道，省下的宽度归项目名。
 */
export function widthTier(width: number): WidthTier {
    if (width >= 320) return 'full'
    if (width >= 270) return 'narrow'
    return 'tight'
}
